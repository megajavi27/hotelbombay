/**
 * Normaliza para buscar: sin tildes y en minúsculas, de modo que escribir
 * "peru" encuentre "Perú" y "mexico" encuentre "México".
 */
export function normalizarTexto(texto: string): string {
  return texto
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim();
}
